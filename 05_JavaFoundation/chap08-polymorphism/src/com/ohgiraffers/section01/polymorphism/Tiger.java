package com.ohgiraffers.section01.polymorphism;

public class Tiger extends Animal {

    public void cry()
    {
        System.out.println("호랑이가 울부짖습니다. 어흥~!");
    }

    public void bite()
    {
        System.out.println("호랑이 물기");
    }

    public void eat()
    {
        System.out.println("호랑이 먹기");
    }

}
