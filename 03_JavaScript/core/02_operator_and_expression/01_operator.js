/**
 * 연산자(Operator)는 두 개 이상의 값(피연산자)를 조작하거나 비교하여 결과를 생성하는 기호이다.
 * 자바스크립트에서 자주 사용되는 연산자에는 산술 연산자, 할당 연산자, 증감 연산자 등이 있다.
 */

// 1. 산술 연산자
let a = 10;
let b = 3;
console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);

// 2. 할당 연산자
let c = 5;
c += 3;
c -= 3;

console.log(c);

// 3. 증감 연산자
let d = 5;

console.log(d++);
console.log(++d);
console.log(d--);
console.log(--d);
